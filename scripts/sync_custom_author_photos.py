"""Reconcile published custom author portraits after the editorial generator runs.

Existing custom articles can be retained rather than regenerated by the editorial
engine, leaving author_headshot_url changes stranded in custom_articles.json.
This narrow presentation-only pass synchronizes the author-card image without
changing the article text, canonical URL, carousel, or editorial identity.
"""
from __future__ import annotations

import json
import re
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
AUTHOR_CARD = re.compile(
    r'<aside\b(?=[^>]*\bclass="[^"]*\barticle-contributor-card\b)[^>]*>[\s\S]*?</aside>',
    re.IGNORECASE,
)
HEADSHOT_IMG = re.compile(
    r'<img\b(?=[^>]*\bclass="[^"]*\barticle-contributor-headshot\b)[^>]*>',
    re.IGNORECASE,
)
SRC = re.compile(r'\bsrc="[^"]*"', re.IGNORECASE)
SAFE_SLUG = re.compile(r"^[a-z0-9][a-z0-9-]*$")
SAFE_IMAGE = re.compile(r"^/images/[a-zA-Z0-9_./-]+\.(?:jpe?g|png|webp)$", re.IGNORECASE)


def sync_author_photo(item: dict, articles_dir: Path) -> bool:
    slug = str(item.get("slug") or "")
    url = str(item.get("author_headshot_url") or "")
    if not url:
        return False
    if not SAFE_SLUG.fullmatch(slug):
        raise ValueError(f"Unsafe custom slug: {slug!r}")
    parsed = urlsplit(url)
    if (
        parsed.scheme != "https"
        or parsed.netloc != "treasurecoast.today"
        or not SAFE_IMAGE.fullmatch(parsed.path)
        or parsed.query
        or parsed.fragment
    ):
        raise ValueError(f"Unsafe author headshot URL for {slug}: {url!r}")

    path = articles_dir / f"{slug}.html"
    if not path.exists():
        # Queued but not yet published; the main generator will create this page.
        return False
    html = path.read_text(encoding="utf-8")
    cards = list(AUTHOR_CARD.finditer(html))
    if len(cards) != 1:
        raise ValueError(f"Expected exactly one author card for {slug}: found {len(cards)}")

    card = cards[0]
    imgs = list(HEADSHOT_IMG.finditer(card.group()))
    if len(imgs) != 1:
        raise ValueError(f"Expected exactly one author portrait for {slug}: found {len(imgs)}")
    img = imgs[0]
    tag = img.group()
    if len(SRC.findall(tag)) != 1:
        raise ValueError(f"Expected exactly one headshot src for {slug}")
    new_tag = SRC.sub(lambda match: f'src="{url}"', tag, count=1)
    if new_tag == tag:
        return False
    updated_card = card.group()[:img.start()] + new_tag + card.group()[img.end():]
    updated = html[:card.start()] + updated_card + html[card.end():]
    path.write_text(updated, encoding="utf-8")
    print(f"Synced existing custom article author photo: {slug}")
    return True


def main(root: Path = ROOT) -> int:
    queue_path = root / "custom_articles.json"
    if not queue_path.exists():
        return 0
    items = json.loads(queue_path.read_text(encoding="utf-8"))
    if not isinstance(items, list):
        raise ValueError("custom_articles.json must be a list")
    changed = 0
    for item in items:
        if isinstance(item, dict) and item.get("author_headshot_url"):
            changed += int(sync_author_photo(item, root / "articles"))
    print(f"Custom author-photo reconciliation: {changed} page(s) updated")
    return changed


if __name__ == "__main__":
    main()
